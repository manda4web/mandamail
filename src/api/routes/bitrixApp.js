function buildAppHtml(data) {
  const safeData = JSON.stringify({
    domain: data.domain,
    member_id: data.member_id,
    auth_id: data.auth_id,
    refresh_id: data.refresh_id,
    server_endpoint: data.server_endpoint,
    application_token: data.application_token,
    auth_expires: data.auth_expires,
  })
    // Prevent closing the <script> tag from inside the JSON (reflected XSS
    // via the public DOMAIN query param) — escape HTML-significant chars.
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026');

  const parts = [];
  parts.push('<!DOCTYPE html>');
  parts.push('<html lang="pt-BR">');
  parts.push('<head>');
  parts.push('<meta charset="utf-8">');
  parts.push('<meta name="viewport" content="width=device-width, initial-scale=1">');
  parts.push('<title>Manda E-mail Parser</title>');
  parts.push('<script src="https://api.bitrix24.com/api/v1/"><\/script>');
  parts.push('<style>');
  parts.push(getAppCss());
  parts.push(getAppCssMore());
  parts.push(getAppCssEnd());
  parts.push('</style>');
  parts.push('</head>');
  parts.push('<body>');
  parts.push('<script id="bitrix-data" type="application/json">' + safeData + '<\/script>');
  parts.push(getLoginHtml());
  parts.push(getAccessDeniedHtml());
  parts.push(getAppShellHtml());
  parts.push(getModalHtml());
  parts.push('<div class="toast" id="toast"></div>');
  parts.push('<script>');
  parts.push(getAppJs());
  parts.push('<\/script>');
  parts.push('</body>');
  parts.push('</html>');
  return parts.join('\n');
}

